    /** Strips a "```java ... ```" markdown fence down to plain compilable Java source. */
    private static String extractJavaCode(String markdownWrapped) {
        if (markdownWrapped == null) return null;
        String s = markdownWrapped.trim();
        if (s.startsWith("```java")) s = s.substring("```java".length());
        else if (s.startsWith("```")) s = s.substring(3);
        if (s.endsWith("```")) s = s.substring(0, s.length() - 3);
        return s.trim();
    }

