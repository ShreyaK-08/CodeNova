    private void seedStudentHistory(String username, int problemOffset, java.util.Map<String, Integer> targets,
                                    int daysSpan, long seed, List<Problem> allProblems) {
        User user = userRepository.findByUsername(username).orElse(null);
        if (user == null) return;

        int totalNeeded = targets.values().stream().mapToInt(Integer::intValue).sum();
        long distinctSolved = submissionRepository.countDistinctSolvedProblemsByUser(user.getId());
        if (distinctSolved >= totalNeeded) {
            certificateService.checkAndAwardMilestones(user.getId());
            return;
        }

        List<Submission> toSave = new ArrayList<>();
        LocalDateTime baseTime = LocalDateTime.now();
        java.util.Random rnd = new java.util.Random(seed);
        int dayOffset = daysSpan;
        int pIdx = problemOffset % allProblems.size();

        for (java.util.Map.Entry<String, Integer> entry : targets.entrySet()) {
            String lang = entry.getKey();
            int needed = entry.getValue();

            for (int i = 0; i < needed; i++) {
                Problem problem = allProblems.get(pIdx % allProblems.size());
                pIdx++;

                // ~20% chance of an initial wrong answer for realistic acceptance rate
                if (rnd.nextInt(100) < 20) {
                    Submission wa = new Submission(
                            user,
                            problem,
                            lang,
                            "// Initial attempt in " + lang + "\n// Logic was incomplete\n"
                    );
                    wa.setStatus(SubmissionStatus.WRONG_ANSWER);
                    wa.setExecutionTime((long) (rnd.nextInt(50) + 15));
                    wa.setMemoryUsed((long) (rnd.nextInt(15000) + 12000));
                    wa.setPassedTestCases(4);
                    wa.setTotalTestCases(10);
                    wa.setFailedTestCases(6);
                    wa.setSubmittedAt(baseTime.minusDays(dayOffset).minusHours(3));
                    toSave.add(wa);
                }

                Submission acc = new Submission(
                        user,
                        problem,
                        lang,
                        "// Optimized solution in " + lang + "\n// Accepted\n"
                );
                acc.setStatus(SubmissionStatus.ACCEPTED);
                acc.setExecutionTime((long) (rnd.nextInt(80) + 10));
                acc.setMemoryUsed((long) (rnd.nextInt(20000) + 15000));
                acc.setPassedTestCases(10);
                acc.setTotalTestCases(10);
                acc.setFailedTestCases(0);
                acc.setSubmittedAt(baseTime.minusDays(dayOffset).minusMinutes(rnd.nextInt(120)));
                toSave.add(acc);

                int step = (i % 3 == 0) ? 0 : (i % 4 == 0 ? 1 : rnd.nextInt(5) + 2);
                dayOffset = Math.max(1, dayOffset - step);
            }
        }

        // Active submissions for yesterday and today
        if (allProblems.size() > 5) {
            Problem pToday = allProblems.get(problemOffset % allProblems.size());
            Submission sToday = new Submission(user, pToday, "JAVA", "// Daily practice\n");
            sToday.setStatus(SubmissionStatus.ACCEPTED);
            sToday.setSubmittedAt(baseTime.minusHours(2));
            sToday.setExecutionTime(25L);
            sToday.setMemoryUsed(18200L);
            sToday.setPassedTestCases(10);
            sToday.setTotalTestCases(10);
            toSave.add(sToday);
        }

        submissionRepository.saveAll(toSave);
        System.out.println(">>> Seeded " + toSave.size() + " submissions for demo user: " + username);
        certificateService.checkAndAwardMilestones(user.getId());
        System.out.println(">>> Awarded certificates for demo user: " + username);
    }

