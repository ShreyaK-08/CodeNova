    private void addSeedHostMcqQuestion(Long assessmentId, Long userId, String questionText,
                                        String[] options, int correctIndex, int marks, String explanation) {
        CreateAssessmentQuestionRequest questionRequest = new CreateAssessmentQuestionRequest();
        questionRequest.setQuestionText(questionText);
        questionRequest.setQuestionType("MCQ");
        questionRequest.setMarks(marks);
        questionRequest.setExplanation(explanation);

        List<CreateAssessmentOptionRequest> optionRequests = new ArrayList<>();
        for (int i = 0; i < options.length; i++) {
            CreateAssessmentOptionRequest option = new CreateAssessmentOptionRequest();
            option.setOptionText(options[i]);
            option.setIsCorrect(i == correctIndex);
            option.setOrderIndex(i + 1);
            optionRequests.add(option);
        }
        questionRequest.setOptions(optionRequests);
        assessmentService.addOwnQuestion(assessmentId, questionRequest, userId);
    }

    private void addSeedProgrammingQuestion(Long assessmentId, Long userId, String title, String problemStatement,
                                             String inputFormat, String outputFormat, String constraints,
                                             String sampleInput, String sampleOutput, int marks,
                                             List<String[]> testCases) {
        CreateAssessmentQuestionRequest questionRequest = new CreateAssessmentQuestionRequest();
        questionRequest.setQuestionText(title);
        questionRequest.setQuestionType("PROGRAMMING");
        questionRequest.setMarks(marks);

        ProgrammingQuestionRequest pqReq = new ProgrammingQuestionRequest();
        pqReq.setProblemStatement(problemStatement);
        pqReq.setInputFormat(inputFormat);
        pqReq.setOutputFormat(outputFormat);
        pqReq.setConstraints(constraints);
        pqReq.setSampleInput(sampleInput);
        pqReq.setSampleOutput(sampleOutput);
        pqReq.setSupportedLanguages("java,python,cpp,javascript,c");
        pqReq.setTimeLimitMs(2000);
        pqReq.setMemoryLimitMb(256);
        questionRequest.setProgrammingQuestion(pqReq);

        AssessmentQuestionDto qDto = assessmentService.addOwnQuestion(assessmentId, questionRequest, userId);

        if (testCases != null && qDto != null) {
            int order = 1;
            for (String[] tc : testCases) {
                ProgrammingTestCaseRequest tcReq = new ProgrammingTestCaseRequest();
                tcReq.setInput(tc[0]);
                tcReq.setExpectedOutput(tc[1]);
                tcReq.setIsHidden(Boolean.parseBoolean(tc[2]));
                tcReq.setOrderIndex(order++);
                tcReq.setDescription(tc.length > 3 ? tc[3] : "Test Case " + (order - 1));
                assessmentService.addOwnTestCase(assessmentId, qDto.getId(), tcReq, userId);
            }
        }
    }

