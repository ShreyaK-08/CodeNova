    /** Creates the problem if it doesn't exist by title; returns the persisted entity either way. */
    private Problem findOrCreateProblem(String title, String description, Difficulty difficulty, String topic,
                                         String constraints, String methodName, String starterCode) {
        return problemRepository.findByTitle(title).orElseGet(() -> {
            Problem p = new Problem(title, description, difficulty, topic, starterCode);
            p.setConstraints(constraints);
            p.setMethodName(methodName);
            Problem saved = problemRepository.save(p);
            System.out.println(">>> Created problem: " + title);
            return saved;
        });
    }

    /** Ensures the problem has exactly 10 test cases matching the curated set (idempotent). */
    private void ensureTestCases(Problem p, String[][] cases) {
        List<TestCase> existing = testCaseRepository.findByProblemId(p.getId());
        if (existing.size() == cases.length) {
            return; // already fully seeded
        }
        if (!existing.isEmpty()) {
            testCaseRepository.deleteAll(existing);
        }
        for (String[] c : cases) {
            String in = (c[0] == null || c[0].isBlank()) ? "-" : c[0];
            String out = (c[1] == null || c[1].isBlank()) ? "-" : c[1];
            testCaseRepository.save(new TestCase(p, in, out, Boolean.parseBoolean(c[2])));
        }
        System.out.println(">>> Seeded " + cases.length + " test cases for: " + p.getTitle());
    }

