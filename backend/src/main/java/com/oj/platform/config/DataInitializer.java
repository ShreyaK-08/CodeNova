    private void createSupportTicketIfMissing(
            String ticketNumber,
            User user,
            String category,
            String subject,
            String description,
            String priority,
            String status,
            User assignedTo,
            Long problemId,
            String problemTitle,
            Long contestId,
            String contestTitle,
            Long assessmentId,
            String assessmentTitle,
            Integer rating,
            String ratingComments,
            LocalDateTime ratedAt,
            LocalDateTime createdAt,
            LocalDateTime updatedAt,
            LocalDateTime resolvedAt,
            LocalDateTime closedAt,
            List<MessageSeed> messages
    ) {
        if (supportRequestRepository.findByTicketNumber(ticketNumber).isPresent()) {
            return;
        }

        SupportRequest req = new SupportRequest();
        req.setTicketNumber(ticketNumber);
        req.setUser(user);
        req.setCategory(category);
        req.setSubject(subject);
        req.setDescription(description);
        req.setPriority(priority != null ? priority : "MEDIUM");
        req.setStatus(status != null ? status : "OPEN");
        req.setAssignedTo(assignedTo);
        req.setProblemId(problemId);
        req.setProblemTitle(problemTitle);
        req.setContestId(contestId);
        req.setContestTitle(contestTitle);
        req.setAssessmentId(assessmentId);
        req.setAssessmentTitle(assessmentTitle);
        req.setRating(rating);
        req.setRatingComments(ratingComments);
        req.setRatedAt(ratedAt);
        req.setCreatedAt(createdAt != null ? createdAt : LocalDateTime.now());
        req.setUpdatedAt(updatedAt != null ? updatedAt : LocalDateTime.now());
        req.setResolvedAt(resolvedAt);
        req.setClosedAt(closedAt);

        SupportRequest savedReq = supportRequestRepository.save(req);

        if (messages != null) {
            for (MessageSeed m : messages) {
                SupportMessage msg = new SupportMessage(savedReq, m.sender, m.role, m.text, m.isInternalNote);
                msg.setCreatedAt(m.createdAt != null ? m.createdAt : LocalDateTime.now());
                supportMessageRepository.save(msg);
            }
        }
    }

    private static class MessageSeed {
        final User sender;
        final String role;
        final String text;
        final boolean isInternalNote;
        final LocalDateTime createdAt;

        MessageSeed(User sender, String role, String text, boolean isInternalNote, LocalDateTime createdAt) {
            this.sender = sender;
            this.role = role;
            this.text = text;
            this.isInternalNote = isInternalNote;
            this.createdAt = createdAt;
        }
    }
